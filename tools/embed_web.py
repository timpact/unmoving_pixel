#!/usr/bin/env python3
"""
Web editor in the dash firmware (ADR 0013): gzips the editor files and writes
them as C arrays with a table (path, MIME type, data, ETag).

    python3 tools/embed_web.py <output .c> <file> [<file> ...]

The files are served under "/<file name>"; index.html also under "/". The
ETag is a hash of the gzipped content, so a browser never keeps an old editor
after a firmware update. gzip with mtime 0: the output only changes with the
files.
"""
import gzip
import hashlib
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
}


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    target, files = sys.argv[1], sys.argv[2:]
    lines = ["/* Generated by tools/embed_web.py - do not edit (ADR 0013) */",
             '#include "web_files.h"', ""]
    table = []
    for i, path in enumerate(files):
        name = os.path.basename(path)
        ext = os.path.splitext(name)[1]
        if ext not in MIME:
            sys.exit(f"{path}: unknown file type")
        with open(path, "rb") as fh:
            data = gzip.compress(fh.read(), compresslevel=9, mtime=0)
        etag = hashlib.sha256(data).hexdigest()[:16]
        lines.append(f"/* {name}: {len(data)} bytes gzipped */")
        lines.append(f"static const unsigned char k_file_{i}[] = {{")
        for k in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[k:k + 16]) + ",")
        lines.append("};")
        table.append(f'    {{"/{name}", "{MIME[ext]}", k_file_{i}, {len(data)}, "\\"{etag}\\""}},')
    lines.append("")
    lines.append("const web_file_t web_files[] = {")
    lines += table
    lines.append("};")
    lines.append(f"const int web_file_count = {len(files)};")
    text = "\n".join(lines) + "\n"
    if os.path.exists(target):
        with open(target, encoding="utf-8") as fh:
            if fh.read() == text:
                return
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
