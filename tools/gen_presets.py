#!/usr/bin/env python3
"""
Built-in presets (ADR 0013): converts presets/{patterns,overlays}/*.json into C
data (common/include/up_presets_builtin.h). Slot order = file name order.

    python3 tools/gen_presets.py <presets dir> <output .c>

Validation follows tools/preset-editor/model.js (validatePattern,
validateOverlay); an invalid file stops the build with a message.
"""
import json
import os
import re
import sys

MAX_SEGMENTS = 2048
NAME_BYTES = 16
FADE_MAX_MM = 1000


def is_int(v, lo, hi):
    return isinstance(v, int) and not isinstance(v, bool) and lo <= v <= hi


def check_name(name, errors):
    if not isinstance(name, str) or not name.strip():
        errors.append("Name fehlt")
    elif len(name.encode("utf-8")) > NAME_BYTES:
        errors.append(f"Name zu lang (max. {NAME_BYTES} Byte)")


def parse_color(text):
    m = re.fullmatch(r"#?([0-9a-fA-F]{6})", str(text).strip())
    if not m:
        return None
    v = int(m.group(1), 16)
    return (v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF


def check_pattern(p):
    errors = []
    check_name(p.get("name"), errors)
    segs = p.get("segments")
    if not isinstance(segs, list) or not segs:
        return errors + ["Mindestens ein Abschnitt nötig"]
    if len(segs) > MAX_SEGMENTS:
        errors.append(f"Höchstens {MAX_SEGMENTS} Abschnitte")
    for i, s in enumerate(segs):
        if not is_int(s.get("length_cm"), 1, 65535):
            errors.append(f"segments[{i}]: Länge 1 … 65535 cm")
        if parse_color(s.get("color")) is None:
            errors.append(f"segments[{i}]: Farbe als #rrggbb")
        if not is_int(s.get("brightness"), 0, 100):
            errors.append(f"segments[{i}]: Helligkeit 0 … 100 %")
    return errors


def check_overlay(o):
    errors = []
    check_name(o.get("name"), errors)
    for k in ("level_start", "level_mid", "level_end"):
        if not is_int(o.get(k), 0, 100):
            errors.append(f"{k}: Pegel 0 … 100 %")
    for k in ("fade_start_mm", "fade_end_mm"):
        if not is_int(o.get(k), 0, FADE_MAX_MM):
            errors.append(f"{k}: Übergang 0 … 1.000 mm")
    if is_int(o.get("fade_start_mm"), 0, 65535) and is_int(o.get("fade_end_mm"), 0, 65535) \
            and o["fade_start_mm"] + o["fade_end_mm"] > FADE_MAX_MM:
        errors.append("Übergänge zusammen max. 1.000 mm")
    return errors


def c_string(s):
    """C string literal with UTF-8 bytes as octal escapes (no trigraph or hex-digit pitfalls)"""
    out = '"'
    for b in s.encode("utf-8"):
        c = chr(b)
        if 0x20 <= b < 0x7F and c not in '"\\?':
            out += c
        else:
            out += "\\%03o" % b
    return out + '"'


def load(directory, kind):
    out = []
    if not os.path.isdir(directory):
        return out
    for f in sorted(os.listdir(directory)):
        if not f.endswith(".json"):
            continue
        path = os.path.join(directory, f)
        with open(path, encoding="utf-8") as fh:
            p = json.load(fh)
        if p.get("format_version") != 1 or p.get("type") != kind:
            sys.exit(f"{path}: format_version 1 and type '{kind}' expected")
        errors = check_pattern(p) if kind == "pattern" else check_overlay(p)
        if errors:
            sys.exit(f"{path}: " + "; ".join(errors))
        out.append((f, p))
    return out


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    root, target = sys.argv[1], sys.argv[2]
    patterns = load(os.path.join(root, "patterns"), "pattern")
    overlays = load(os.path.join(root, "overlays"), "overlay")

    lines = [
        "/* Generated by tools/gen_presets.py from presets/ - do not edit (ADR 0013) */",
        '#include "up_presets_builtin.h"',
        "",
    ]
    for i, (f, p) in enumerate(patterns):
        lines.append(f"/* {f} */")
        lines.append(f"static const up_segment_t k_pattern_{i}[] = {{")
        for s in p["segments"]:
            r, g, b = parse_color(s["color"])
            lines.append(f"    {{{s['length_cm']}, {s['brightness']}, {r}, {g}, {b}}},")
        lines.append("};")
    lines.append("")
    lines.append("const up_builtin_pattern_t up_builtin_patterns[] = {")
    for i, (f, p) in enumerate(patterns):
        lines.append(f"    {{{c_string(p['name'])}, {len(p['segments'])}, k_pattern_{i}}},")
    if not patterns:
        lines.append("    {0},")
    lines.append("};")
    lines.append(f"const int up_builtin_pattern_count = {len(patterns)};")
    lines.append("")
    lines.append("const up_builtin_overlay_t up_builtin_overlays[] = {")
    for f, o in overlays:
        lines.append(f"    {{{c_string(o['name'])}, {{UP_OVERLAY_TYPE_EDGE_FADE, {o['level_start']}, {o['level_mid']}, "
                     f"{o['level_end']}, {o['fade_start_mm']}, {o['fade_end_mm']}}}}}, /* {f} */")
    if not overlays:
        lines.append("    {0},")
    lines.append("};")
    lines.append(f"const int up_builtin_overlay_count = {len(overlays)};")

    text = "\n".join(lines) + "\n"
    if os.path.exists(target):
        with open(target, encoding="utf-8") as fh:
            if fh.read() == text:
                return
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
